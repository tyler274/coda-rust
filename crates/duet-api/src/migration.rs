//! The Duet schema as a SeaORM migration chain.
//!
//! The SQL files in `crates/duet-api/migrations` are the coda-app schema,
//! copied verbatim. Each file is one migration: it opens its own transaction
//! and records its version in `public.schema_migrations`. SeaORM records the
//! same versions in `duet_seaql_migrations`, separate from the front-door
//! chain, because both chains can run on one database. A rerun applies nothing.
//! The files have no rollback.

use sea_orm_migration::prelude::*;

/// Where this chain records applied versions. Not `seaql_migrations`, which
/// the front-door chain also avoids, so the two chains can share a database.
pub const MIGRATION_TABLE: &str = "duet_seaql_migrations";

/// The vendored Duet schema, oldest first.
pub struct Migrator;

#[async_trait::async_trait]
impl MigratorTrait for Migrator {
    fn migrations() -> Vec<Box<dyn MigrationTrait>> {
        FILES
            .iter()
            .map(|(name, sql)| Box::new(SqlFile { name, sql }) as Box<dyn MigrationTrait>)
            .collect()
    }

    fn migration_table_name() -> DynIden {
        MIGRATION_TABLE.into_iden()
    }
}

/// Applies every migration not yet recorded. A second call applies nothing.
pub async fn up(database_url: &str) -> Result<(), DbErr> {
    let db = sea_orm::Database::connect(database_url).await?;
    Migrator::up(&db, None).await
}

struct SqlFile {
    name: &'static str,
    sql: &'static str,
}

impl MigrationName for SqlFile {
    fn name(&self) -> &str {
        self.name
    }
}

#[async_trait::async_trait]
impl MigrationTrait for SqlFile {
    // Each file already begins and commits its own transaction.
    fn use_transaction(&self) -> Option<bool> {
        Some(false)
    }

    async fn up(&self, manager: &SchemaManager) -> Result<(), DbErr> {
        manager
            .get_connection()
            .execute_unprepared(self.sql)
            .await?;
        Ok(())
    }
}

