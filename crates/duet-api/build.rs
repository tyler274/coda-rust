//! Emits the vendored Duet migration list: filename order, the SHA-256 of each
//! file, and a function returning the file's SQL. Checksums are computed at
//! build time, so an edited migration fails the build rather than at deploy.

use std::fs;

use sha2::{Digest, Sha256};

fn main() {
    println!("cargo:rerun-if-changed=migrations");
    let mut files: Vec<_> = fs::read_dir("migrations")
        .expect("migrations directory")
        .map(|entry| entry.expect("migration entry").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "sql"))
        .collect();
    files.sort();

    let mut out = String::from(
        "// @generated by build.rs from crates/duet-api/migrations\n\
         /// Vendored Duet migrations as `(filename, sha256)`, in apply order.\n\
         pub static MIGRATIONS: &[(&str, &str)] = &[\n",
    );
    let mut bodies = String::from(
        "/// The SQL of one vendored migration, compiled in from the file.\n\
         pub fn migration_sql(file: &str) -> &'static str {\n    match file {\n",
    );
    for path in &files {
        let name = path.file_name().unwrap().to_str().unwrap();
        let digest = Sha256::digest(fs::read(path).unwrap());
        let digest = digest
            .iter()
            .map(|byte| format!("{byte:02x}"))
            .collect::<String>();
        out.push_str(&format!("    (\"{name}\", \"{digest}\"),\n"));
        let literal = path.canonicalize().unwrap().to_str().unwrap().to_owned();
        bodies.push_str(&format!(
            "        \"{name}\" => include_str!(\"{literal}\"),\n"
        ));
    }
    out.push_str("];\n");
    bodies.push_str("        other => panic!(\"unknown Duet migration: {other}\"),\n    }\n}\n");

    let destination =
        std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("duet_migrations.rs");
    fs::write(destination, out + &bodies).unwrap();
}
