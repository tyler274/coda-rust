//! Every default location the pipeline reads or writes, in one place.
//!
//! The tool's inputs (catalog, terminology cache, coda-gym ranges, story tables,
//! authoring guide) live in this crate's `data/`. The patients themselves, their
//! seeds and accepted ledgers, live apart from the tool in the workspace's
//! `patients/`. Drafts, the bank and other derived output live under the ignored
//! `target/patient-bank/`. `PATIENT_BANK_DATA`, `PATIENT_BANK_PATIENTS` and
//! `PATIENT_BANK_ROOT` override the three directories, so a scratch copy can be
//! checked or authored in without touching the checkout.

use std::env;
use std::path::{Path, PathBuf};

/// The workspace root this crate was built in.
pub fn workspace_root() -> PathBuf {
    let crate_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    crate_dir
        .parent()
        .and_then(Path::parent)
        .expect("crates/patient-bank sits two levels below the workspace root")
        .to_path_buf()
}

/// The pipeline's inputs.
pub fn data_dir() -> PathBuf {
    env::var_os("PATIENT_BANK_DATA").map_or_else(
        || Path::new(env!("CARGO_MANIFEST_DIR")).join("data"),
        PathBuf::from,
    )
}

/// The patient set: seeds and accepted ledgers.
pub fn patients_dir() -> PathBuf {
    env::var_os("PATIENT_BANK_PATIENTS")
        .map_or_else(|| workspace_root().join("patients"), PathBuf::from)
}

/// Drafts, the bank and the vocabulary.
pub fn root() -> PathBuf {
    env::var_os("PATIENT_BANK_ROOT").map_or_else(
        || workspace_root().join("target/patient-bank"),
        PathBuf::from,
    )
}

pub fn catalog() -> PathBuf {
    data_dir().join("catalog.json")
}

/// What real practice looks like, metric by metric; `realism` is its only writer.
pub fn realism() -> PathBuf {
    data_dir().join("realism.json")
}

/// Terminology service answers behind the catalog; the catalog build is its only writer.
pub fn terminology_cache() -> PathBuf {
    data_dir().join("terminology-cache.json")
}

/// coda-gym's lab labels and reference ranges.
pub fn gym_lab_ranges() -> PathBuf {
    data_dir().join("gym-lab-ranges.json")
}

/// Who every patient is, designed once and authored against.
pub fn seeds() -> PathBuf {
    patients_dir().join("seeds.json")
}

/// Accepted ledgers, `<unit>.json`, written only by `check`.
pub fn ledgers() -> PathBuf {
    patients_dir().join("ledgers")
}

/// The tables `stories` draws unwritten patients' clinical stories from.
pub fn stories() -> PathBuf {
    data_dir().join("stories.json")
}

pub fn authoring_guide() -> PathBuf {
    data_dir().join("authoring-guide.md")
}

/// The catalog's labels as authors see them, regenerated by `brief`, `check` and `preview`.
pub fn vocabulary() -> PathBuf {
    root().join("vocabulary.md")
}

/// The official HL7 FHIR R4 4.0.1 JSON schema (`fhir.schema.json`), downloaded once.
pub fn schema() -> PathBuf {
    root().join("fhir.schema.json")
}

/// The Coda Agents Roger fixture's resources.
pub fn roger_fixture() -> PathBuf {
    workspace_root().join("submodules/coda-agents/docs/local-product-fixtures/internal_resources")
}
